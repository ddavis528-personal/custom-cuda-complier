#!/usr/bin/env bash
# Writes test/sfu-hard-cases.txt: every FP32 input at which a double-precision
# reference is too near an FP32 midpoint to say how the exact value rounds, for
# each FP SFU function, with its correctly rounded value judged by mpmath at 400
# bits (tools/judge-sfu.py). tools/check-sfu-math takes those values from here,
# so the gate needs no mpmath. An exhaustive run: about 40 minutes on 4 cores.
set -euo pipefail
cd "$(dirname "$0")/.."
[ -x build/check-sfu-math ] || { echo "build/check-sfu-math not built"; exit 1; }
python3 -c "import mpmath" || { echo "needs mpmath (pip install mpmath)"; exit 1; }
TMP=$(mktemp -d); trap 'rm -rf "$TMP"' EXIT
for f in rcp rsqrt sqrt ex2 lg2 sin cos; do
  build/check-sfu-math --all "$f" > "$TMP/$f.txt" || { grep -v '^HARD' "$TMP/$f.txt"; exit 1; }
done
{
  echo "# Generated by tools/gen-sfu-hard-cases.sh: <fn> <x> <correctly rounded fn(x)>,"
  echo "# FP32 bit patterns, judged by mpmath for every input a double reference cannot."
  cat "$TMP"/*.txt | awk '/^HARD/ {print $2, $3}' | sort -k1,1 -k2,2 | python3 -I tools/judge-sfu.py
} > test/sfu-hard-cases.txt
echo "test/sfu-hard-cases.txt: $(grep -vc '^#' test/sfu-hard-cases.txt) inputs"
